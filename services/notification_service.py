"""Event-driven notifications: in-app (always), email and WhatsApp (when configured).

Every attempt is recorded in the notifications table with the provider's real outcome.
Dedupe keys prevent the same event being sent twice to the same applicant.
"""
from __future__ import annotations

import html
from typing import Dict, Optional

from database import db_manager as db
from services import email_service, whatsapp_service

BRAND = "DO! u want"
SYSTEM = "SEATWISEE"


def _template(conn, event: str, ctx: Dict[str, str]) -> Dict[str, str]:
    inst = db.get_site_text(conn, "institute_name", "the institute")
    name = ctx.get("name", "Applicant")
    appid = ctx.get("app_id", "")
    prog = ctx.get("program", "")
    T = {
        "account_registered": ("Welcome to SEATWISEE!",
            f"Dear {name}, your {BRAND} account at {inst} is ready. Sign in to complete your admission application."),
        "application_submitted": ("Application Received & Under Review",
            f"Dear {name}, your application {appid} has been received with {ctx.get('n_prefs','')} ranked program(s). We will notify you when the allotment is published."),
        "eligibility_verified": ("Eligibility verified",
            f"Dear {name}, your application {appid} has been verified as eligible for at least one of your ranked programs."),
        "provisional_offer": ("Provisional seat allotment",
            f"Dear {name}, congratulations! Application {appid} has been provisionally allotted a seat in {prog}. Sign in to accept your offer."),
        "admission_confirmed": ("Admission confirmed",
            f"Dear {name}, your admission to {prog} (application {appid}) is confirmed. Welcome to {inst}!"),
        "waitlisted": ("Waitlist update",
            f"Dear {name}, application {appid} is currently waitlisted. Seats may open up through withdrawals; we will notify you automatically."),
        "reallocated": ("Allocation updated",
            f"Dear {name}, following a reallocation your application {appid} is now allotted to {prog}. Sign in for details."),
        "withdrawal_requested": ("Withdrawal request received",
            f"Dear {name}, we received your withdrawal request for application {appid}. The admissions office will confirm it shortly."),
        "withdrawal_confirmed": ("Withdrawal confirmed",
            f"Dear {name}, your withdrawal for application {appid} has been processed and your seat released. Your record is retained for audit."),
        "appeal_submitted": ("Appeal submitted",
            f"Dear {name}, your appeal for {prog} (application {appid}) has been submitted and will be evaluated by the admissions office."),
        "appeal_evaluated": ("Appeal decision",
            f"Dear {name}, your appeal for {prog} has been {ctx.get('decision','evaluated')}. Sign in to see the details."),
        "test": ("Test notification from SEATWISEE", f"Hello {name}, this is a test message from {BRAND} · {inst}."),
    }
    subject, body = T.get(event, (event.replace("_", " ").title(), ctx.get("body", "")))
    return {"subject": subject, "body": body}


def _html(subject: str, body: str, inst: str) -> str:
    return f"""<div style="font-family:Inter,Arial,sans-serif;max-width:560px;margin:auto;border:1px solid #e5e7eb;border-radius:14px;overflow:hidden">
<div style="background:#0B1F3A;color:#fff;padding:18px 22px"><div style="font-weight:800;font-size:18px">{html.escape(BRAND)}</div><div style="opacity:.75;font-size:12px">{html.escape(inst)}</div></div>
<div style="padding:22px;color:#0f172a;line-height:1.6"><h2 style="margin:0 0 10px;font-size:18px">{html.escape(subject)}</h2><p>{html.escape(body)}</p>
<p style="color:#64748b;font-size:12px;margin-top:18px">This message was generated by {SYSTEM}. Please do not reply.</p></div></div>"""


def notify(conn, applicant_id: Optional[int], event: str, ctx: Optional[Dict[str, str]] = None, *,
           channels=("in_app", "email", "whatsapp"), dedupe: Optional[str] = None) -> Dict[str, str]:
    """Create one notification per channel. Returns {channel: status}."""
    ctx = dict(ctx or {})
    row = conn.execute("SELECT * FROM applicants WHERE id = ?", (applicant_id,)).fetchone() if applicant_id else None
    if row:
        ctx.setdefault("name", row["name"]); ctx.setdefault("app_id", db.app_id(row["id"]))
    msg = _template(conn, event, ctx)
    inst = db.get_site_text(conn, "institute_name", "the institute")
    results: Dict[str, str] = {}
    for ch in channels:
        key = f"{applicant_id}:{ch}:{dedupe or event}" if applicant_id else None
        if ch == "in_app":
            status, detail = "sent", "delivered in portal"
        elif ch == "email":
            if row and row["email"]:
                status, detail = email_service.send_email(row["email"], f"[{BRAND}] {msg['subject']}", _html(msg["subject"], msg["body"], inst), msg["body"])
            else:
                status, detail = "skipped", "no email address"
        else:
            if row and row["phone"]:
                status, detail = whatsapp_service.send_whatsapp(row["phone"], f"{BRAND} · {msg['subject']}\n{msg['body']}")
            else:
                status, detail = "skipped", "no phone number"
        nid = db.insert_notification(conn, applicant_id=applicant_id, channel=ch, event=event, subject=msg["subject"], body=msg["body"],
                                     status=status, provider_response=detail, dedupe_key=key)
        results[ch] = status if nid else "duplicate"
    return results


def send_test(conn, to_email: str, to_phone: str) -> Dict[str, str]:
    """Admin test-send. Not deduped; recorded with applicant_id NULL."""
    inst = db.get_site_text(conn, "institute_name", "the institute")
    msg = _template(conn, "test", {"name": "Admin"})
    out = {}
    if to_email:
        status, detail = email_service.send_email(to_email, f"[{BRAND}] {msg['subject']}", _html(msg["subject"], msg["body"], inst), msg["body"])
        db.insert_notification(conn, applicant_id=None, channel="email", event="test", subject=msg["subject"], body=f"to {to_email}", status=status, provider_response=detail)
        out["email"] = f"{status}: {detail}"
    if to_phone:
        status, detail = whatsapp_service.send_whatsapp(to_phone, f"{BRAND} · {msg['subject']}\n{msg['body']}")
        db.insert_notification(conn, applicant_id=None, channel="whatsapp", event="test", subject=msg["subject"], body=f"to {to_phone}", status=status, provider_response=detail)
        out["whatsapp"] = f"{status}: {detail}"
    return out


def integration_status() -> Dict[str, dict]:
    return {
        "email": {"configured": email_service.is_configured(), "text": email_service.status_text()},
        "whatsapp": {"configured": whatsapp_service.is_configured(), "text": whatsapp_service.status_text()},
    }
